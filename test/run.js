// Comments allowed in generated files: markers, deploy/.env (the secrets checklist) and these
// configuration hints. flarops.yaml and FLAROPS.md are documentation.
const ALLOWED_GENERATED_COMMENTS = new Set([
  '#autogenerated by flarops',
  '# Added by Flarops',
  '# KEY: "VALUE"',
  "# false when this project's own API gateway already covers these routes -",
  '# set to true to also expose them directly, bypassing the gateway.',
  '# Third-party components declared in docker-compose that the application',
  '# references but this repository does not build. Images are pinned exactly as',
  '# docker-compose declared them.',
  "# instanceType and volumeSize are filled in by CI from Terraform's outputs -",
  '# change them in deploy/terraform/variables.tf, not here.',
  '# Filled in by CI from the registry credentials. Leave null: nothing secret',
  '# belongs in this committed file.',
  '# Set by the PR-capsule workflow to the node a capsule is placed on. Leave',
  '# empty here.',
  '# Worker nodes, by slot number. The PR-capsule workflow adds and removes them;',
  '# there is no need to edit this by hand.',
  '# Read by the server and every worker. A change applies to NEW nodes only -',
  '# replace an existing one (terraform workspace select main, then',
  '# terraform apply -replace=...) to upgrade it.',
  '# Changes to the AMI or to user_data reach only new instances; replace this',
  '# one deliberately to apply them here (terraform workspace select main, then',
  "# terraform apply -replace=...). The cluster's data lives on its root volume.",
]);
function generatedComments(dir) {
  const git = (args) => execFileSync('git', args, { cwd: dir }).toString().split('\n').filter(Boolean);
  const written = git(['status', '--porcelain', '-uall'])
    .filter(l => l.startsWith('??') || /\.(git|docker)ignore$/.test(l))
    .map(l => l.slice(3));
  const found = [];
  for (const rel of written) {
    if (['flarops.yaml', 'FLAROPS.md', 'AGENTS.md', 'CLAUDE.md', 'deploy/.env'].includes(rel) || rel.startsWith('.keys/') || /\.(gif|png)$/.test(rel)) continue;
    const go = rel.endsWith('.go');
    const html = rel.endsWith('.html');
    fs.readFileSync(path.join(dir, rel), 'utf8').split('\n').forEach((line, i) => {
      const hash = !html && /^\s*#(?!!)/.test(line) && !ALLOWED_GENERATED_COMMENTS.has(line.trim());
      if (hash || /\{\{-?\s*\/\*/.test(line) ||
          (go && /\/\/(?!go:)/.test(line.replace(/"[^"]*"|`[^`]*`/g, ''))) ||
          (html && /<!--|\/\*/.test(line))) {
        found.push(`${rel}:${i + 1}: ${line.trim().slice(0, 80)}`);
      }
    });
  }
  return found;
}

// A "${" left in generated output is a JS template literal escaped wrong.
function noUnexpandedJs(dir, rel) {
  const text = fs.readFileSync(path.join(dir, rel), 'utf8');
  const bad = [];
  if (/\$\{'/.test(text)) bad.push("nested-quote interpolation");
  if (/\bundefined\b/.test(text)) bad.push("literal 'undefined'");
  if (/\[object Object\]/.test(text)) bad.push("stringified object");
  return bad;
}

function duplicateTopLevelKeys(dir) {
  const text = fs.readFileSync(path.join(dir, 'deploy/helm/values.yaml'), 'utf8');
  const seen = new Map();
  for (const line of text.split('\n')) {
    const m = line.match(/^([A-Za-z_][A-Za-z0-9_]*):/);
    if (m) seen.set(m[1], (seen.get(m[1]) || 0) + 1);
  }
  return [...seen.entries()].filter(([, n]) => n > 1).map(([k]) => k);
}

// Every secretKeyRef must be a key CI puts in the Secret.
function secretRefsWithoutSource(dir) {
  const templatesDir = path.join(dir, 'deploy/helm/templates');
  const wf = fs.readFileSync(path.join(dir, '.github/workflows/deploy.yml'), 'utf8');
  const provided = new Set([...wf.matchAll(/SECRET_ENV_([A-Z0-9_]+):/g)].map(m => m[1]));
  provided.add('DB_PASSWORD'); // carried by its own SECRET_DB_PASSWORD line
  // <KEY>_URLENCODED twins are derived in the Secret, never passed by CI.
  for (const key of [...provided]) provided.add(`${key}_URLENCODED`);
  const missing = new Set();
  for (const file of fs.readdirSync(templatesDir)) {
    if (!file.endsWith('.yaml')) continue;
    const text = fs.readFileSync(path.join(templatesDir, file), 'utf8');
    for (const m of text.matchAll(/secretKeyRef:\s*\n\s*name:[^\n]*\n\s*key:\s*([A-Za-z0-9_]+)/g)) {
      if (!provided.has(m[1])) missing.add(`${file}: ${m[1]}`);
    }
  }
  return [...missing];
}

